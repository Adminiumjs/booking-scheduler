/**
 * Area bundle: **chrome**.
 *
 * Owns the App shell (`app/App.tsx`), every shared component under
 * `components/`, the zustand store's own copy (toasts, validation messages),
 * and the `lib/` layer — including the counted-noun and unit strings that
 * `lib/format.ts` composes.
 *
 * Add keys to all eight locales at once. `en-US` is the source of truth: every
 * key it carries becomes part of `MessageKey`, so a key present here and
 * missing from a translation silently falls back to English at runtime rather
 * than breaking the build — check both when you add one.
 *
 * Plural keys carry `|`-separated variants in the locale's own CLDR order:
 *   en/de/fr/da  one|other
 *   cs           one|few|other
 *   zh-CN/zh-TW  other        (a single variant — no `|`)
 *   ar-EG        zero|one|two|few|many|other
 *
 * A locale only needs `|` where its grammar actually forks: `chrome.day.open`
 * has one invariant form in English and German and three in Czech, and the
 * runtime reads each bundle's own string, so that is written per locale rather
 * than padded out with duplicates.
 *
 * fr-FR uses typographic apostrophes and a NO-BREAK SPACE before `? ! : ;`.
 * zh-TW is translated independently of zh-CN — never character-converted.
 */
