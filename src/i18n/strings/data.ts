/**
 * Area bundle: **data modules** — `data/demo.ts`, `data/source.ts`,
 * `data/types.ts` and everything under `data/screens/`.
 *
 * UI LABELS ONLY: column headings, status names, category names, filter
 * labels, tab names, empty-state copy. The in-fiction seed records themselves
 * — client names, service names, review bodies, blog posts, addresses — stay
 * in English: they are the salon's own content, not the product's chrome, and
 * a German reader still sees a salon that trades in English.
 *
 * The line between the two is drawn per *record*, not per string. A treatment,
 * a package, a job advert, a journal post and a promo are things Lumen Studio
 * wrote, so their names and prose stay as written; a status, a filter chip, a
 * settings row, a rating word and a loyalty rule are things the product says
 * about them, so those are keys. Where the two meet in one line the key is a
 * template with a hole in it — `data.ledger.visit` is `'{service} with
 * {staff}'`, never three fragments the screen concatenates, because which
 * order those go in is the translator's decision and not English's.
 *
 * Nothing here is a pre-formatted number, date, time, price or percentage.
 * Those left the seed data entirely: the modules now carry `dateISO` strings,
 * minute counts and bare numbers, and the screens spell them with `Intl`
 * through `lib/format.ts`. `'9:00 AM – 6:00 PM'`, `'$39'`, `'Jul 14, 2026'`
 * and `'1,240'` were each a statement about English that stopped being true
 * one locale over.
 *
 * Add keys to all eight locales at once. Plural keys carry `|`-separated
 * variants in the locale's own CLDR order:
 *   en/de/fr/da  one|other
 *   cs           one|few|other
 *   zh-CN/zh-TW  other        (a single variant — no `|`)
 *   ar-EG        zero|one|two|few|many|other
 *
 * fr-FR uses typographic apostrophes and a NO-BREAK SPACE before `? ! : ;`.
 * zh-TW is translated independently of zh-CN — never character-converted.
 */
